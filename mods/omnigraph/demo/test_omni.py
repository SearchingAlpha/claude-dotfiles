#!/usr/bin/env python3
"""Tests for the omnigraph demo CLI, and the fixture the mod's tests read.

    python3 -m unittest discover -s mods/omnigraph/demo -p 'test_*.py'
    python3 mods/omnigraph/demo/test_omni.py --regen   # rewrite tests/demo-store.ts

The mod's TypeScript tests replay the demo through tests/demo-store.ts: the
seed store and the store after two mutations, written by this CLI. The last
test here fails when that file no longer matches what the CLI writes, so the
store format the CLI writes and the one the mod reads cannot drift apart.

Python 3.9, standard library only; each test runs the CLI in a temporary folder.
"""

import json
import os
import subprocess
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
CLI = os.path.join(HERE, "omni.py")
FIXTURE = os.path.join(HERE, "..", "tests", "demo-store.ts")
STORE = "graphs/dev.omni"

CREATE = {"id": "iss-offline-conflict-toast", "title": "Conflict toast hides unsynced edits"}
ADD = {"epic": "epc-offline-sync", "issue": "iss-offline-conflict-toast"}


def omni(cwd, *args):
    """Runs the CLI in `cwd`; returns (exit code, stdout, stderr)."""
    done = subprocess.run(
        [sys.executable, "-I", CLI, *args],
        cwd=cwd,
        capture_output=True,
        text=True,
        env={**os.environ, "OMNIGRAPH_STORE": STORE},
        timeout=60,
    )
    return done.returncode, done.stdout, done.stderr


def read(cwd, name):
    with open(os.path.join(cwd, STORE, name), encoding="utf-8") as fh:
        return fh.read()


def jsonl(cwd, name):
    return [json.loads(line) for line in read(cwd, name).splitlines() if line.strip()]


def snapshot(cwd):
    return {name: read(cwd, f"{name}.{ext}") for name, ext in (("manifest", "json"), ("nodes", "jsonl"), ("edges", "jsonl"))}


def fixture_text():
    """What tests/demo-store.ts should hold: the seed, then the store after each mutation."""
    with tempfile.TemporaryDirectory() as cwd:
        omni(cwd, "init")
        seed = snapshot(cwd)
        omni(cwd, "mutate", "create_issue", "--params", json.dumps(CREATE))
        created = snapshot(cwd)
        omni(cwd, "mutate", "add_issue_to_epic", "--params", json.dumps(ADD))
        added = snapshot(cwd)

    def store(texts):
        return "{\n" + "".join(f"  {key}: {json.dumps(texts[key])},\n" for key in ("manifest", "nodes", "edges")) + "}"

    return (
        "// Generated by `python3 mods/omnigraph/demo/test_omni.py --regen` from the demo CLI\n"
        "// (demo/omni.py): the seed store, then the store after `mutate create_issue` and\n"
        "// `mutate add_issue_to_epic`. Synthetic data. Do not edit by hand.\n"
        f"export const CREATE_PARAMS = {json.dumps(json.dumps(CREATE))}\n"
        f"export const ADD_PARAMS = {json.dumps(json.dumps(ADD))}\n\n"
        f"export const SEED = {store(seed)}\n\n"
        f"export const AFTER_CREATE = {store(created)}\n\n"
        f"export const AFTER_ADD = {store(added)}\n"
    )


class StoreFormat(unittest.TestCase):
    def test_init_writes_the_three_files_and_the_queries(self):
        with tempfile.TemporaryDirectory() as cwd:
            code, out, _ = omni(cwd, "init")
            self.assertEqual(code, 0)
            self.assertEqual(json.loads(out)["nodes"], 31)
            manifest = json.loads(read(cwd, "manifest.json"))
            nodes, edges = jsonl(cwd, "nodes.jsonl"), jsonl(cwd, "edges.jsonl")
            self.assertEqual(manifest["format"], "omnigraph/1")
            self.assertEqual(manifest["name"], "dev.omni")
            self.assertEqual((manifest["nodes"], manifest["edges"]), (len(nodes), len(edges)))
            self.assertEqual(sum(manifest["labels"].values()), len(nodes))
            self.assertEqual(sum(manifest["edge_types"].values()), len(edges))
            ids = {node["id"] for node in nodes}
            for node in nodes:
                self.assertEqual(set(node), {"id", "label", "props"})
                self.assertIsInstance(node["props"]["name"], str)
            for edge in edges:
                self.assertIn(edge["from"], ids)
                self.assertIn(edge["to"], ids)
            self.assertTrue(os.path.isfile(os.path.join(cwd, "queries", "queries.gq")))
            self.assertFalse(os.path.exists(os.path.join(cwd, STORE, "ops.jsonl")))

    def test_init_refuses_an_existing_store_unless_forced(self):
        with tempfile.TemporaryDirectory() as cwd:
            omni(cwd, "init")
            self.assertEqual(omni(cwd, "init")[0], 1)
            self.assertEqual(omni(cwd, "init", "--force")[0], 0)


class Mutations(unittest.TestCase):
    def test_each_mutation_changes_the_store_and_logs_one_op(self):
        with tempfile.TemporaryDirectory() as cwd:
            omni(cwd, "init")
            before = json.loads(read(cwd, "manifest.json"))
            steps = [
                ("create_issue", CREATE, 1, 0),
                ("add_issue_to_epic", ADD, 0, 1),
                ("assign_issue_owner", {"issue": CREATE["id"], "owner": "act-nadia"}, 0, 1),
                ("link_blocks", {"blocker": CREATE["id"], "blocked": "iss-offline-merge"}, 0, 1),
            ]
            for op, params, d_nodes, d_edges in steps:
                code, out, err = omni(cwd, "mutate", op, "--query", "queries/queries.gq", "--store", STORE, "--params", json.dumps(params))
                self.assertEqual(code, 0, err)
                self.assertEqual((json.loads(out)["dNodes"], json.loads(out)["dEdges"]), (d_nodes, d_edges))
            after = json.loads(read(cwd, "manifest.json"))
            self.assertEqual((after["nodes"], after["edges"]), (before["nodes"] + 1, before["edges"] + 3))
            self.assertNotEqual(after["version"], before["version"])
            ops = jsonl(cwd, "ops.jsonl")
            self.assertEqual([(o["kind"], o["op"], o["ok"]) for o in ops], [("mutate", s[0], True) for s in steps])
            for record in ops:
                self.assertIsInstance(record["t"], int)
                self.assertGreaterEqual(record["ms"], 0)

    def test_queries_read_and_log_without_writing(self):
        with tempfile.TemporaryDirectory() as cwd:
            omni(cwd, "init")
            omni(cwd, "mutate", "create_issue", "--params", json.dumps({**CREATE, "epic": "epc-offline-sync"}))
            version = json.loads(read(cwd, "manifest.json"))["version"]
            code, out, _ = omni(cwd, "query", "epic_open_issues", "--params", json.dumps({"epic": "epc-offline-sync"}))
            self.assertEqual(code, 0)
            self.assertIn("iss-offline-conflict-toast  Conflict toast hides unsynced edits", out)
            self.assertIn("(5 rows)", out)
            self.assertIn("iss-offline-merge", omni(cwd, "query", "blocked")[1])
            self.assertEqual(json.loads(read(cwd, "manifest.json"))["version"], version)
            self.assertEqual(jsonl(cwd, "ops.jsonl")[-1]["kind"], "query")

    def test_refusals_exit_1_log_the_error_and_change_nothing(self):
        with tempfile.TemporaryDirectory() as cwd:
            omni(cwd, "init")
            version = json.loads(read(cwd, "manifest.json"))["version"]
            code, _, err = omni(cwd, "mutate", "link_blocks", "--params", json.dumps({"blocker": "iss-x", "blocked": "iss-offline-merge"}))
            self.assertEqual(code, 1)
            self.assertIn("no node 'iss-x'", err)
            last = jsonl(cwd, "ops.jsonl")[-1]
            self.assertEqual((last["ok"], last["error"]), (False, "no node 'iss-x'"))
            self.assertEqual(omni(cwd, "mutate", "nope", "--query", "queries/queries.gq", "--params", "{}")[0], 1)
            self.assertEqual(json.loads(read(cwd, "manifest.json"))["version"], version)

    def test_bad_params_exit_2_and_log_the_failure(self):
        with tempfile.TemporaryDirectory() as cwd:
            omni(cwd, "init")
            version = json.loads(read(cwd, "manifest.json"))["version"]
            for params, error in (("{not json", "--params is not JSON: "), ("[1]", "--params must be a JSON object")):
                code, _, err = omni(cwd, "mutate", "link_blocks", "--params", params)
                self.assertEqual(code, 2, err)
                self.assertNotIn("Traceback", err)
                last = jsonl(cwd, "ops.jsonl")[-1]
                self.assertEqual((last["kind"], last["op"], last["ok"]), ("mutate", "link_blocks", False))
                self.assertTrue(last["error"].startswith(error), last["error"])
            self.assertEqual(len(jsonl(cwd, "ops.jsonl")), 2)
            self.assertEqual(json.loads(read(cwd, "manifest.json"))["version"], version)

    def test_wrongly_typed_params_exit_1_with_a_reason_and_log_it(self):
        with tempfile.TemporaryDirectory() as cwd:
            omni(cwd, "init")
            version = json.loads(read(cwd, "manifest.json"))["version"]
            cases = (
                ({"title": "x", "labels": 5}, "param labels must be a string or a list of strings"),
                ({"title": "x", "id": 5}, "param id must be a string, not int"),
                ({"title": "x", "owner": ["act-nadia"]}, "param owner must be a string, not list"),
                ({"title": "x", "labels": ["lbl-crdt", 7]}, "param labels must be a string or a list of strings"),
            )
            for params, error in cases:
                code, _, err = omni(cwd, "mutate", "create_issue", "--params", json.dumps(params))
                self.assertEqual(code, 1, err)
                self.assertNotIn("Traceback", err)
                self.assertEqual(err.strip().splitlines(), [f"omnigraph: mutate create_issue: {error}"])
                last = jsonl(cwd, "ops.jsonl")[-1]
                self.assertEqual((last["op"], last["ok"], last["error"]), ("create_issue", False, error))
            self.assertEqual(json.loads(read(cwd, "manifest.json"))["version"], version)
            # One label as a string is a list of one, not its characters.
            code, out, err = omni(cwd, "mutate", "create_issue", "--params", json.dumps({"title": "Tagged once", "labels": "lbl-crdt"}))
            self.assertEqual(code, 0, err)
            self.assertIn({"from": "iss-tagged-once", "type": "tagged", "to": "lbl-crdt", "props": {}}, jsonl(cwd, "edges.jsonl"))

    def test_no_store_exits_1_and_creates_nothing(self):
        with tempfile.TemporaryDirectory() as cwd:
            code, _, err = omni(cwd, "query", "blocked")
            self.assertEqual(code, 1)
            self.assertIn("run `omnigraph init` first", err)
            self.assertEqual(os.listdir(cwd), [])


class Fixture(unittest.TestCase):
    def test_the_mods_fixture_matches_what_the_cli_writes(self):
        with open(FIXTURE, encoding="utf-8") as fh:
            committed = fh.read()
        self.assertEqual(committed, fixture_text(), "run: python3 mods/omnigraph/demo/test_omni.py --regen")


if __name__ == "__main__":
    if sys.argv[1:] == ["--regen"]:
        with open(FIXTURE, "w", encoding="utf-8") as fh:
            fh.write(fixture_text())
        print(f"wrote {os.path.normpath(FIXTURE)}")
    else:
        unittest.main()
